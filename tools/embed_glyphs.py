#!/usr/bin/env python3
"""embed_glyphs.py <glyphs dir> <out .c>: the Switch's button icons (tools/switch_glyphs.sh's bundles) as C data.

The NRO writes them next to itself at start (source/glyphs.c), so a player needs no tool for the L, R, + and -
icons. Made from the game's own LB, RB, Menu and View icons (switch_glyphs.py): the same for every copy of the game's
1.10.1 build.
"""
import os
import sys


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    src, out = sys.argv[1], sys.argv[2]
    names = sorted(n for n in os.listdir(src) if n.endswith(".bundle"))
    with open(out, "w") as f:
        f.write("/* glyphs_data.c -- generated by tools/embed_glyphs.py: the Switch's button icons (L, R, +, -) as the\n"
                " * game's own bundles, remade by tools/switch_glyphs.py from the game's LB, RB, Menu and View icons.\n"
                " * source/glyphs.c writes them next to the NRO. */\n\n#include <stddef.h>\n#include <stdint.h>\n\n")
        for i, n in enumerate(names):
            data = open(os.path.join(src, n), "rb").read()
            f.write("static const uint8_t g%d[%d] = {\n" % (i, len(data)))
            for j in range(0, len(data), 20):
                f.write("  " + ", ".join("0x%02x" % b for b in data[j:j + 20]) + ",\n")
            f.write("};\n")
        f.write("\nconst struct { const char *name; const uint8_t *data; size_t size; } g_glyph_files[] = {\n")
        for i, n in enumerate(names):
            f.write('  { "%s", g%d, sizeof g%d },\n' % (n, i, i))
        f.write("};\nconst size_t g_glyph_count = %d;\n" % len(names))
    print("%d bundles -> %s" % (len(names), out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
